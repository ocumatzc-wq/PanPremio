-- ------------------------------------------------------------
-- 1) Clientes
-- ------------------------------------------------------------
CREATE TABLE Clientes (
    id_cliente      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    codigo          VARCHAR2(20),
    nombre          VARCHAR2(100) NOT NULL,
    apellidos       VARCHAR2(100) NOT NULL,
    email           VARCHAR2(100),
    telefono        VARCHAR2(20),
    saldo_puntos    NUMBER(10) DEFAULT 0 NOT NULL,
    activo          NUMBER(1)  DEFAULT 1 NOT NULL,
    fecha_registro  DATE       DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_clientes        PRIMARY KEY (id_cliente),
    CONSTRAINT uq_clientes_codigo UNIQUE (codigo),
    CONSTRAINT ck_clientes_saldo  CHECK (saldo_puntos >= 0),
    CONSTRAINT ck_clientes_activo CHECK (activo IN (0, 1))
);

-- ------------------------------------------------------------
-- 2) Productos (sandwiches, bebidas y acompanamientos)
-- ------------------------------------------------------------
CREATE TABLE Productos (
    id_producto   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    codigo        VARCHAR2(20),
    categoria     VARCHAR2(20)  NOT NULL,
    nombre        VARCHAR2(100) NOT NULL,
    precio        NUMBER(10,2) DEFAULT 0 NOT NULL,
    existencia    NUMBER(10)   DEFAULT 0 NOT NULL,
    activo        NUMBER(1)    DEFAULT 1 NOT NULL,
    CONSTRAINT pk_productos           PRIMARY KEY (id_producto),
    CONSTRAINT uq_productos_codigo    UNIQUE (codigo),
    CONSTRAINT ck_productos_categoria CHECK (categoria IN ('Sandwich', 'Bebida', 'Acompanamiento')),
    CONSTRAINT ck_productos_precio    CHECK (precio >= 0),
    CONSTRAINT ck_productos_existencia CHECK (existencia >= 0),
    CONSTRAINT ck_productos_activo    CHECK (activo IN (0, 1))
);

-- ------------------------------------------------------------
-- 3) Menus completos
-- ------------------------------------------------------------
CREATE TABLE Menus (
    id_menu   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    codigo    VARCHAR2(20),
    nombre    VARCHAR2(100) NOT NULL,
    precio    NUMBER(10,2) DEFAULT 0 NOT NULL,
    activo    NUMBER(1)    DEFAULT 1 NOT NULL,
    CONSTRAINT pk_menus           PRIMARY KEY (id_menu),
    CONSTRAINT uq_menus_codigo    UNIQUE (codigo),
    CONSTRAINT ck_menus_precio    CHECK (precio >= 0),
    CONSTRAINT ck_menus_activo    CHECK (activo IN (0, 1))
);

-- ------------------------------------------------------------
-- 4) Composicion de cada menu (que productos lo forman)
-- ------------------------------------------------------------
CREATE TABLE Menu_Composicion (
    id_menu      NUMBER(10) NOT NULL,
    id_producto  NUMBER(10) NOT NULL,
    cantidad     NUMBER(10) DEFAULT 1 NOT NULL,
    CONSTRAINT pk_menu_composicion PRIMARY KEY (id_menu, id_producto),
    CONSTRAINT fk_mc_menu          FOREIGN KEY (id_menu)     REFERENCES Menus (id_menu),
    CONSTRAINT fk_mc_producto      FOREIGN KEY (id_producto) REFERENCES Productos (id_producto),
    CONSTRAINT ck_mc_cantidad      CHECK (cantidad > 0)
);

-- ------------------------------------------------------------
-- 5) Movimientos de inventario (abastecimientos y ventas)
-- ------------------------------------------------------------
CREATE TABLE Movimientos_Inventario (
    id_movimiento  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_producto    NUMBER(10) NOT NULL,
    tipo           VARCHAR2(20) NOT NULL,
    cantidad       NUMBER(10) NOT NULL,
    fecha          DATE DEFAULT SYSDATE NOT NULL,
    referencia     VARCHAR2(60),
    CONSTRAINT pk_mov_inventario PRIMARY KEY (id_movimiento),
    CONSTRAINT fk_mov_inv_prod   FOREIGN KEY (id_producto) REFERENCES Productos (id_producto),
    CONSTRAINT ck_mov_inv_tipo   CHECK (tipo IN ('ENTRADA', 'SALIDA', 'AJUSTE')),
    CONSTRAINT ck_mov_inv_cant   CHECK (cantidad <> 0)
);

-- ------------------------------------------------------------
-- 6) Pedidos
-- ------------------------------------------------------------
CREATE TABLE Pedidos (
    id_pedido         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_cliente        NUMBER(10) NOT NULL,
    fecha_pedido      DATE DEFAULT SYSDATE NOT NULL,
    total             NUMBER(10,2) DEFAULT 0 NOT NULL,
    puntos_generados  NUMBER(10) DEFAULT 0 NOT NULL,
    estado            VARCHAR2(15) DEFAULT 'PENDIENTE' NOT NULL,
    CONSTRAINT pk_pedidos        PRIMARY KEY (id_pedido),
    CONSTRAINT fk_pedidos_cliente FOREIGN KEY (id_cliente) REFERENCES Clientes (id_cliente),
    CONSTRAINT ck_pedidos_estado CHECK (estado IN ('PENDIENTE', 'PAGADO', 'ENTREGADO', 'ANULADO')),
    CONSTRAINT ck_pedidos_total  CHECK (total >= 0),
    CONSTRAINT ck_pedidos_puntos CHECK (puntos_generados >= 0)
);

-- ------------------------------------------------------------
-- 7) Detalle de cada pedido (productos o menus)
-- ------------------------------------------------------------
CREATE TABLE Detalle_Pedidos (
    id_detalle       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_pedido        NUMBER(10) NOT NULL,
    id_producto      NUMBER(10),
    id_menu          NUMBER(10),
    cantidad         NUMBER(10) NOT NULL,
    precio_unitario  NUMBER(10,2) NOT NULL,
    subtotal         NUMBER(10,2) NOT NULL,
    puntos           NUMBER(10) DEFAULT 0 NOT NULL,
    CONSTRAINT pk_detalle_pedidos PRIMARY KEY (id_detalle),
    CONSTRAINT fk_detalle_pedido  FOREIGN KEY (id_pedido)   REFERENCES Pedidos (id_pedido),
    CONSTRAINT fk_detalle_prod    FOREIGN KEY (id_producto) REFERENCES Productos (id_producto),
    CONSTRAINT fk_detalle_menu    FOREIGN KEY (id_menu)     REFERENCES Menus (id_menu),
    CONSTRAINT ck_detalle_item    CHECK (
        (id_producto IS NOT NULL AND id_menu IS NULL)
        OR (id_menu IS NOT NULL AND id_producto IS NULL)),
    CONSTRAINT ck_detalle_cant    CHECK (cantidad > 0),
    CONSTRAINT ck_detalle_montos  CHECK (precio_unitario >= 0 AND subtotal >= 0)
);

-- ------------------------------------------------------------
-- 8) Pagos
-- ------------------------------------------------------------
CREATE TABLE Pagos (
    id_pago    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_pedido  NUMBER(10) NOT NULL,
    tipo       VARCHAR2(10) NOT NULL,
    monto      NUMBER(10,2) NOT NULL,
    recibido   NUMBER(10,2),
    cambio     NUMBER(10,2) DEFAULT 0 NOT NULL,
    referencia VARCHAR2(40),
    fecha_pago DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_pagos         PRIMARY KEY (id_pago),
    CONSTRAINT fk_pagos_pedido  FOREIGN KEY (id_pedido) REFERENCES Pedidos (id_pedido),
    CONSTRAINT ck_pagos_tipo    CHECK (tipo IN ('EFECTIVO', 'TARJETA')),
    CONSTRAINT ck_pagos_monto   CHECK (monto > 0),
    CONSTRAINT ck_pagos_ref     CHECK (tipo <> 'TARJETA' OR referencia IS NOT NULL)
);

-- ------------------------------------------------------------
-- 9) Movimientos de puntos (acumulacion y canje)
-- ------------------------------------------------------------
CREATE TABLE Movimientos_Puntos (
    id_movimiento    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_cliente       NUMBER(10) NOT NULL,
    tipo             VARCHAR2(20) NOT NULL,
    puntos           NUMBER(10) NOT NULL,
    fecha_movimiento DATE DEFAULT SYSDATE NOT NULL,
    referencia       VARCHAR2(60),
    CONSTRAINT pk_mov_puntos     PRIMARY KEY (id_movimiento),
    CONSTRAINT fk_mov_puntos_cli FOREIGN KEY (id_cliente) REFERENCES Clientes (id_cliente),
    CONSTRAINT ck_mov_puntos_tipo CHECK (tipo IN ('ACUMULACION', 'CANJE', 'AJUSTE')),
    CONSTRAINT ck_mov_puntos_puntos CHECK (puntos <> 0)
);

-- ------------------------------------------------------------
-- 10) Catalogo de recompensas
-- ------------------------------------------------------------
CREATE TABLE Recompensas (
    id_recompensa     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    codigo            VARCHAR2(20),
    nombre            VARCHAR2(100) NOT NULL,
    puntos_requeridos NUMBER(10) NOT NULL,
    id_producto       NUMBER(10),
    id_menu           NUMBER(10),
    activo            NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT pk_recompensas        PRIMARY KEY (id_recompensa),
    CONSTRAINT uq_recompensas_codigo UNIQUE (codigo),
    CONSTRAINT fk_recompensas_prod   FOREIGN KEY (id_producto) REFERENCES Productos (id_producto),
    CONSTRAINT fk_recompensas_menu   FOREIGN KEY (id_menu)     REFERENCES Menus (id_menu),
    CONSTRAINT ck_recompensas_item   CHECK (
        (id_producto IS NOT NULL AND id_menu IS NULL)
        OR (id_menu IS NOT NULL AND id_producto IS NULL)),
    CONSTRAINT ck_recompensas_puntos CHECK (puntos_requeridos > 0),
    CONSTRAINT ck_recompensas_activo CHECK (activo IN (0, 1))
);

-- ------------------------------------------------------------
-- 11) Canjes realizados
-- ------------------------------------------------------------
CREATE TABLE Canjes (
    id_canje       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    id_cliente     NUMBER(10) NOT NULL,
    id_recompensa  NUMBER(10) NOT NULL,
    puntos_usados  NUMBER(10) NOT NULL,
    fecha_canje    DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_canjes          PRIMARY KEY (id_canje),
    CONSTRAINT fk_canjes_cliente  FOREIGN KEY (id_cliente)    REFERENCES Clientes (id_cliente),
    CONSTRAINT fk_canjes_recomp   FOREIGN KEY (id_recompensa) REFERENCES Recompensas (id_recompensa),
    CONSTRAINT ck_canjes_puntos   CHECK (puntos_usados > 0)
);

